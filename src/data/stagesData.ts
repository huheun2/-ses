// Helper: pick N questions from a stage pool.
// Always place the foundational 1st question first to introduce the core concept cleanly,
// while shuffling the remaining questions to prevent simple position-based memorization.
export function getRandomQuestionsForStage(stageId: number, count = 5): Question[] {
  const stage = STAGES.find(s => s.id === stageId);
  if (!stage || stage.questionPool.length === 0) return [];
  const [firstQuestion, ...restQuestions] = stage.questionPool;
  const shuffledRest = [...restQuestions].sort(() => Math.random() - 0.5);
  return [firstQuestion, ...shuffledRest].slice(0, Math.min(count, stage.questionPool.length));
}
